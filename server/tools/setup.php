<?php
/**
 * Prepares server/form-config.php for the order administration. Run it on your own computer:
 *
 *     php server/tools/setup.php
 *
 * It creates the key that encrypts customer data (once) and sets an administrator's name and password.
 * The password is stored only as a hash. Run it again to change a password or add another administrator,
 * then upload form-config.php to the server again.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$file = dirname(__DIR__) . '/form-config.php';
if (!is_file($file)) {
    fwrite(STDERR, "Súbor $file neexistuje. Skopírujte form-config.example.php ako form-config.php a spustite to znova.\n");
    exit(1);
}

$source = (string) file_get_contents($file);
$config = (array) require $file;

function ask(string $question): string
{
    fwrite(STDOUT, $question);
    return trim((string) fgets(STDIN));
}

// The data key is created once and never replaced: orders already stored could not be read with a new one.
$key = (string) ($config['data_key'] ?? '');
$decoded = base64_decode($key, true);
if ($decoded === false || strlen($decoded) !== 32) {
    $key = base64_encode(random_bytes(32));
    echo "Vytvoril som nový šifrovací kľúč.\n";
}

$admins = is_array($config['admins'] ?? null) ? $config['admins'] : [];
if ($admins) {
    echo 'Existujúci administrátori: ' . implode(', ', array_keys($admins)) . "\n";
}

$name = ask('Prihlasovacie meno (napr. dalibor): ');
if (!preg_match('/^[a-z0-9._-]{3,30}$/', $name)) {
    fwrite(STDERR, "Meno môže obsahovať len malé písmená bez diakritiky, číslice, bodku, pomlčku a podčiarkovník (3 až 30 znakov).\n");
    exit(1);
}
echo "Heslo sa pri písaní zobrazuje. Použite aspoň 12 znakov, najlepšie vetu alebo heslo zo správcu hesiel.\n";
$password = ask('Heslo: ');
if (mb_strlen($password) < 12) {
    fwrite(STDERR, "Heslo je príliš krátke (menej ako 12 znakov). Nič som nezmenil.\n");
    exit(1);
}
if ($password !== ask('Heslo ešte raz: ')) {
    fwrite(STDERR, "Heslá sa nezhodujú. Nič som nezmenil.\n");
    exit(1);
}
$admins[$name] = password_hash($password, PASSWORD_DEFAULT);

$lines = ["    // >>> generated by tools/setup.php. Re-run it to change. Never delete data_key: stored orders could not be read."];
$lines[] = "    'data_key' => " . var_export($key, true) . ',';
$lines[] = "    'admins' => [";
foreach ($admins as $admin => $hash) {
    $lines[] = '        ' . var_export((string) $admin, true) . ' => ' . var_export((string) $hash, true) . ',';
}
$lines[] = '    ],';
$lines[] = '    // <<< generated';
$block = implode("\n", $lines) . "\n";

if (preg_match('~^[ \t]*// >>> generated.*?^[ \t]*// <<< generated[^\n]*\n~ms', $source, $match)) {
    $updated = str_replace($match[0], $block, $source);
} else {
    $end = strrpos($source, '];');
    if ($end === false) {
        fwrite(STDERR, "V súbore $file som nenašiel koniec nastavení (];). Nič som nezmenil.\n");
        exit(1);
    }
    $updated = substr($source, 0, $end) . "\n" . $block . substr($source, $end);
}

// Check the result before replacing the real file.
$draft = $file . '.new';
file_put_contents($draft, $updated);
try {
    $check = (array) require $draft;
    $valid = ($check['data_key'] ?? '') === $key && isset($check['admins'][$name]) && password_verify($password, $check['admins'][$name]);
} catch (Throwable $e) {
    $valid = false;
}
if (!$valid) {
    unlink($draft);
    fwrite(STDERR, "Nové nastavenia sa nepodarilo overiť. Pôvodný súbor zostal bez zmeny.\n");
    exit(1);
}
rename($draft, $file);

echo "\nHotovo. Administrátor \"$name\" je nastavený v server/form-config.php.\n";
echo "Teraz nahrajte form-config.php na server (cez FTP), aby sa zmena prejavila.\n";
